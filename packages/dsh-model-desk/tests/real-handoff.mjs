/**
 * Real-channel end-to-end check: subagent delegation and session switching.
 *
 * Manual (not part of npm test): boots the shipped web profile in-process
 * against the real channel recorded in tests/real-providers.local.json, and
 * proves what the stub suites cannot - the child and the relayed session really
 * run on the channel and really answer:
 *   - a roster entry with a provider/model -> the child descriptor and its
 *     first request both name that route, and it produces an answer;
 *   - a blank roster route -> the child inherits the parent latest request
 *     route (before that request it falls back to the creation options);
 *   - newSession carries the parent selection into the new session, which runs
 *     a real turn;
 *   - newSession.onFinish [done] opens that session by itself on a finish.
 *
 * Prerequisites: bundle first (the plugin loads from lib/index.js; src carries
 * decorators a strip-only loader rejects), and the machine proxy in the
 * environment (the gateway resets direct Node TLS): HTTPS_PROXY and
 * NODE_USE_ENV_PROXY. See tools.md for the exact command lines.
 *
 * Free-tier caveat: the channel quota can end a turn before it answers (one
 * QUOTA code on the selected route). Read the session log under the workspace
 * before blaming the plugin: a refused turn proves nothing either way.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
  boot, createRuntimeResolution, loadOverlayPatches, loadProfile, PluginPackages,
} from '@deepseek-ai/dsh-app-boot'
import { provideCmdline } from '@deepseek-ai/dsh-cmdline'

const HERE = fileURLToPath(new URL('.', import.meta.url))
const REPO = fileURLToPath(new URL('../../../', import.meta.url))
const PKG = `${REPO}packages/dsh-model-desk`
const DSH_INSTALL = `${REPO}node_modules/@deepseek-ai/dsh/package.json`
const WORK = process.env.DSH_E2E_WORK ?? `${HERE}.workspace-real-handoff`
const HOME = `${HERE}.dshhome-real-handoff`
const OVERLAY = `${HERE}real-handoff.overlay.yml`

const creds = JSON.parse(readFileSync(`${PKG}/tests/real-providers.local.json`, 'utf8'))
const channelA = creds.channels.find(c => c.id === 'real-a')
const channelC = creds.channels.find(c => c.id === 'real-c')
if (channelA === undefined || channelC === undefined) {
  console.error('credential file must define real-a and real-c')
  process.exit(2)
}

// `channels[].models` is a list of model ids (strings), not objects.
const models = channel => channel.models.map(id =>
  `          - { id: '${id}', name: '${id}', contextWindow: 65536, maxTokens: 8192 }`).join('\n')

writeFileSync(OVERLAY, `# Generated by .tmp/e2e-real.mjs — do not edit.
- id: llm-deepseek
  disabled: true
- id: llm-deepseek-account
  disabled: true
- id: session-title-llm
  disabled: true

- id: session-persistence-jsonl
  config:
    root: './.e2e-sessions'
    compression: none

- id: llm-pi-ai
  config:
    providers:
      real-a:
        apiKeyEnv: REAL_A_KEY
        displayName: 'Real A'
        api: 'openai-completions'
        baseURL: '${channelA.baseURL}'
        models:
${models(channelA)}
      real-c:
        apiKeyEnv: REAL_C_KEY
        displayName: 'Real C'
        api: 'openai-completions'
        baseURL: '${channelC.baseURL}'
        models:
${models(channelC)}

- id: agent-default-model
  config:
    provider: real-a
    model: step-5-preview

- insert:
    - id: model-desk
      name: '${PKG}/lib/index.js'
      config:
        enabled: true
        policyVersion: 2
        # An empty chain is a configuration: the router deliberately does not
        # take over, so these checks measure handoff, never routing.
        defaultChainId: real
        chains:
          - id: real
            candidates: []
        handoff:
          enabled: true
          roster:
            - id: worker
              name: worker
              role: work
              purpose: 干活的角色（钉死模型）
              instructions: 只回一句话，不要用工具
              provider: real-a
              model: step-5-preview
            - id: inherit
              name: inherit
              role: work
              purpose: 跟随父会话的模型
              instructions: 只回一句话，不要用工具
          limits:
            maxNewSessionsPerUserMessage: 5
          newSession:
            onFinish: [done]
`)

rmSync(HOME, { recursive: true, force: true })
rmSync(`${WORK}/.e2e-sessions`, { recursive: true, force: true })
mkdirSync(HOME, { recursive: true })
mkdirSync(WORK, { recursive: true })
process.env.DSH_HOME = HOME
// The overlay points each provider at an apiKeyEnv; an in-process boot reads
// them from this process, so they have to be set before the plugin resolves
// credentials (listing models without a key leaves the catalog empty and every
// send is refused with `session/model-unavailable`).
process.env.REAL_A_KEY = channelA.apiKey
process.env.REAL_C_KEY = channelC.apiKey
process.chdir(WORK)

const profile = loadProfile('desk-e2e', 'web', DSH_INSTALL, undefined, { userLayer: false })
writeFileSync(fileURLToPath(new URL('./cordis.yml', `file:///${profile.dir.replaceAll('\\', '/')}/`)), '[]\n')
const overlays = [loadOverlayPatches('desk-e2e', OVERLAY)]
const moduleLayers = [{
  packageName: 'model-desk',
  packageDir: PKG,
  patchPaths: [OVERLAY],
  patches: [],
}]
const resolution = await createRuntimeResolution({
  installAnchor: DSH_INSTALL,
  profile: { ...profile, layers: [...profile.layers, ...moduleLayers] },
})

/** @type {import('@deepseek-ai/cordis').Context} */
let ctx
try {
  ctx = await boot(
    'desk-e2e',
    fileURLToPath(new URL('./cordis.yml', `file:///${profile.dir.replaceAll('\\', '/')}/`)),
    [...profile.layers.flatMap(layer => layer.patches), ...overlays.flat()],
    async (composing) => {
      provideCmdline(composing, { args: ['--no-open', '--port', '0'], exit: () => {} })
      composing.provide('profileContext', {
        name: 'web', dir: profile.dir, patchPath: profile.patchPath, installAnchor: DSH_INSTALL,
        cwd: WORK, home: HOME,
        startedBundles: profile.layers.map(layer => layer.packageName),
        overlays: overlays.flat(), telemetryDisabledEnv: undefined,
      })
      await composing.plugin(PluginPackages, { resolution })
    },
  )
} catch (error) {
  console.log(`boot failed: ${error instanceof Error ? error.stack : String(error)}`)
  process.exit(1)
}

let failures = 0
const check = (label, condition, detail) => {
  if (condition) console.log(`    ok  ${label}`)
  else {
    failures += 1
    console.log(`    FAIL ${label}${detail === undefined ? '' : `: ${detail}`}`)
  }
}

// ---------- helpers over the durable logs ----------

const walk = dir => readdirSync(dir, { withFileTypes: true })
  .flatMap(entry => entry.isDirectory() ? walk(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`])

/** Every session log under the workspace, newest event first ignored. */
const logs = () => {
  try {
    return walk(`${WORK}/.e2e-sessions`).filter(file => file.endsWith('.jsonl'))
  } catch {
    return []
  }
}

/** Parse one session log by the session id it belongs to. */
const eventsOf = id => {
  const file = logs().find(candidate => candidate.includes(id))
  if (file === undefined) return []
  return readFileSync(file, 'utf8').trim().split('\n').filter(Boolean).map(line => JSON.parse(line))
}

const waitFor = async (probe, label, timeoutMs = 120_000) => {
  const started = Date.now()
  while (Date.now() - started < timeoutMs) {
    const value = probe()
    if (value !== undefined) return value
    await new Promise(resolve => setTimeout(resolve, 500))
  }
  console.log(`    ..  timed out waiting for ${label}`)
  return undefined
}

const routeOf = events => {
  const header = events.find(event => event.type === 'request/header')
  const config = header?.data?.header?.config
  return config === undefined ? undefined : `${config.provider}/${config.model}`
}

const answerOf = events => events
  .filter(event => event.type === 'assistant/message')
  .flatMap(event => event.data.message.content)
  .filter(block => block.type === 'text')
  .map(block => block.text)
  .join(' ')
  .trim()

// ---------- the parent session: one real turn ----------

const controller = ctx.get('sessionController')
const registry = ctx.get('agents')
const tool = ctx.get('tools').get('handoff')
check('the web composition mounts sessionController and the handoff tool', controller !== undefined && tool !== undefined)

const created = await controller.create({ cwd: WORK, reusable: () => false })
const parentId = String(created.sessionId)
const agent = registry.get(created.sessionId)
await controller.selectModel({ sessionId: created.sessionId, provider: 'real-a', model: 'glm-5.2' })
agent.followup('只回复两个字：收到')
// The parent's own first turn is a harness artefact: a session created
// in-process and followed up immediately ends turn 1 inside DSH's own loop with
// "Cannot read properties of undefined (reading 'kind')", before any routing
// listener could matter. The parent's route is therefore checked at the end,
// off the turn a delegation settlement wakes (that is the header
// `carrySelection` reads).

// ---------- 1. delegate, roster pinned to a model ----------

const pinnedReceipt = await tool.execute(
  { action: 'delegate', rosterId: 'worker', task: '只回复两个字：子代理' },
  { agent, signal: new AbortController().signal },
)
const pinnedChild = String(pinnedReceipt?.child ?? '')
check('delegate answers a child id', pinnedChild !== '', JSON.stringify(pinnedReceipt))
const pinnedEvents = await waitFor(() => {
  const events = eventsOf(pinnedChild)
  return answerOf(events) === '' ? undefined : events
}, 'the pinned child turn')
const pinnedDescriptor = (pinnedEvents ?? []).find(event => event.type === 'subagent/descriptor')?.data
check('the pinned child ran on the roster route', routeOf(pinnedEvents ?? []) === 'real-a/step-5-preview',
  JSON.stringify({ route: routeOf(pinnedEvents ?? []), descriptor: `${pinnedDescriptor?.agentProvider}/${pinnedDescriptor?.agentModel}` }))
check('the pinned child produced a real answer', answerOf(pinnedEvents ?? []) !== '',
  JSON.stringify(answerOf(pinnedEvents ?? [])))

// ---------- 2. pin the parent's own route, so "inherit" is distinguishable ----------

// `resolveChildAgentOptions` reads the parent's **latest request header** and
// only falls back to the creation options before its first request, so an
// inheriting child tests nothing until the parent has a header of its own. Wake
// it explicitly (the session was created in-process, so nothing has sent a
// message yet) and wait for the header, which must be the model we selected —
// not the profile default the blanks would otherwise inherit.
agent.followup('只回复两个字：继续')
const parentRouted = await waitFor(() => {
  const events = eventsOf(parentId)
  return routeOf(events) === undefined ? undefined : events
}, 'the parent request header', 240_000)
check('the parent recorded a request on the selected route', routeOf(parentRouted ?? []) === 'real-a/glm-5.2',
  JSON.stringify({ route: routeOf(parentRouted ?? []), default: 'real-a/step-5-preview' }))

const inheritReceipt = await tool.execute(
  { action: 'delegate', rosterId: 'inherit', task: '只回复两个字：继承' },
  { agent, signal: new AbortController().signal },
)
const inheritChild = String(inheritReceipt?.child ?? '')
const inheritEvents = await waitFor(() => {
  const events = eventsOf(inheritChild)
  return answerOf(events) === '' ? undefined : events
}, 'the inheriting child turn')
check('a blank roster route inherits the parent route', routeOf(inheritEvents ?? []) === 'real-a/glm-5.2',
  JSON.stringify({ route: routeOf(inheritEvents ?? []), answer: answerOf(inheritEvents ?? []) }))
check('the inheriting child produced a real answer', answerOf(inheritEvents ?? []) !== '',
  JSON.stringify(answerOf(inheritEvents ?? [])))

// ---------- 3. newSession: carry the selection, wake it for real ----------

const relayReceipt = await tool.execute(
  { action: 'newSession', handoffNote: '接着做一件小事：说一句你好' },
  { agent, signal: new AbortController().signal },
)
const relayedId = String(relayReceipt?.newSession ?? '')
check('newSession answers a new session id', relayedId !== '' && relayedId !== parentId, JSON.stringify(relayReceipt))
const relayedEvents = await waitFor(() => {
  const events = eventsOf(relayedId)
  return answerOf(events) === '' ? undefined : events
}, 'the relayed session turn', 240_000)
check('the relayed session carried the parent route (not the default)', routeOf(relayedEvents ?? []) === 'real-a/glm-5.2',
  JSON.stringify({ route: routeOf(relayedEvents ?? []), default: 'real-a/step-5-preview' }))
check('the relayed session produced a real answer', answerOf(relayedEvents ?? []) !== '',
  JSON.stringify(answerOf(relayedEvents ?? [])))

// ---------- 4. onFinish: a configuration-driven switch, no model decision ----------

const finishReceipt = await tool.execute(
  { action: 'finish', outcome: 'done', handoffNote: '做完了，下一步说一句再见', report: 'e2e' },
  { agent, signal: new AbortController().signal },
)
const autoId = String(finishReceipt?.newSessionId ?? '')
check('finish with the configured outcome opened a session by itself', autoId !== '' && autoId !== parentId,
  JSON.stringify(finishReceipt))
const autoEvents = await waitFor(() => {
  const events = eventsOf(autoId)
  return answerOf(events) === '' ? undefined : events
}, 'the onFinish session turn', 240_000)
check('the onFinish session ran on the parent route', routeOf(autoEvents ?? []) === 'real-a/glm-5.2',
  JSON.stringify(routeOf(autoEvents ?? [])))
check('the onFinish session produced a real answer', answerOf(autoEvents ?? []) !== '',
  JSON.stringify(answerOf(autoEvents ?? [])))

if (typeof ctx.dispose === 'function') await ctx.dispose()
console.log(failures === 0 ? '\n0 failure(s)' : `\n${failures} failure(s)`)
process.exit(failures === 0 ? 0 : 1)
