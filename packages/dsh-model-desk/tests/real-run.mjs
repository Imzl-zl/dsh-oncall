/**
 * Real-provider composition test: boot the actual headless Loader against the
 * live newapi gateway and assert the failover on the durable session log.
 *
 * Unlike run.mjs (deterministic stub, hermetic), this one spends real requests
 * on the free channels recorded in tests/real-providers.local.json (gitignored,
 * never committed) and needs the machine's proxy in the environment. It is a
 * manual verification tool, not part of the hermetic suite.
 *
 *   $env:HTTPS_PROXY = 'http://127.0.0.1:7890'   # machine proxy, see tools.md
 *   $env:NODE_USE_ENV_PROXY = '1'
 *   node packages/dsh-model-desk/tests/real-run.mjs [server|transport]
 *
 * `server` (default): the user's selection is a channel-B model that answers
 * every request with an upstream 500. `transport`: the selection is a
 * hand-declared route pointing at the discard port, so the failure is a real
 * connection refusal — the deterministic TRANSPORT path.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
// Which failure codes this scenario switches on, from the production table
// rather than from a second copy of the code list here: a gateway's 5xx can
// reach us as PI_AI_ERROR when its in-stream error text carries no status
// (pi-ai maps a 5xx only when it can read one, dsh-llm-pi-ai/lib/index.js:
// 1451-1458), and that code is switchable through the fallback `other` key.
import { switchOnKeyOf } from '../src/defaults.ts'

/** One declaration for both sides: the overlay's config and the assertion. */
const SWITCH_ON = {
  rateLimit: true, server: true, timeout: true, transport: true,
  emptyResponse: false, invalidRequest: false, other: true,
}
const switchOnYaml = Object.entries(SWITCH_ON).map(([key, on]) => `${key}: ${on}`).join(', ')

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, '..', '..', '..')
const DSH_HOME = path.join(here, '.dshhome-real')
const scenario = process.argv[2] ?? 'server'
if (scenario !== 'server' && scenario !== 'transport') {
  console.error('usage: real-run.mjs [server|transport]')
  process.exit(2)
}

let creds
try {
  creds = JSON.parse(readFileSync(path.join(here, 'real-providers.local.json'), 'utf8'))
} catch {
  console.error('missing tests/real-providers.local.json (gitignored) — create it first')
  process.exit(2)
}
const channelA = creds.channels.find(c => c.id === 'real-a')
const channelB = creds.channels.find(c => c.id === 'real-b')
// `server` selects a model on channel C: the id that actually 5xxes lives
// there, and a route the router never saw registered fails as NO_ADAPTER
// instead of reaching the gateway.
const channelC = creds.channels.find(c => c.id === 'real-c')
if (channelA === undefined || channelB === undefined) {
  console.error('credentials file must define channels real-a and real-b')
  process.exit(2)
}
if (scenario === 'server' && channelC === undefined) {
  console.error('the `server` scenario needs channel real-c in the credentials file')
  process.exit(2)
}

// The scenario: the user's own selection is a model that cannot serve the
// request — a real upstream 5xx (`server`) or a real connection refusal
// (`transport`) — and the chain's backup is a channel-A model that answers.
//
// The broken ids are live-gateway facts, not test constants: `real-run.mjs`
// used to point `server` at `real-b/gpt-6-astra`, but that model now lives on
// `real-c` (502) while `real-b` answers (`tests/real-providers.local.json`
// records the same note). Re-check with a one-message probe before blaming the
// router when this fails.
const SCENARIOS = {
  server: { broken: { provider: 'real-c', model: 'gpt-6-astra' }, backup: { provider: 'real-a', model: 'step-5-preview' } },
  transport: { broken: { provider: 'real-dead', model: 'kimi-k3' }, backup: { provider: 'real-a', model: 'step-5-preview' } },
}
const { broken: BROKEN, backup: BACKUP } = SCENARIOS[scenario]

const models = (channel, ids) => ids.map(id => ({
  id,
  name: id,
  contextWindow: 65_536,
  maxTokens: 8_192,
}))

// The overlay inserts the BUILT artifact, never src/index.ts: the host class
// carries @Remote decorators and the shipped CLI loads plugins through Node's
// strip-only type removal, which rejects decorators ("Invalid or unexpected
// token") — the router then never activates and every assertion below fails on
// NO_ADAPTER. Run the package's bundle script first (see tools.md).
const overlay = `# Generated by real-run.mjs — do not edit.
- id: llm-deepseek
  disabled: true
- id: llm-deepseek-account
  disabled: true
- id: session-title-llm
  disabled: true

- id: session-persistence-jsonl
  config:
    root: './.sessions'
    compression: none

- id: llm-pi-ai
  config:
    providers:
      real-a:
        apiKeyEnv: REAL_A_KEY
        displayName: 'Real A (newapi)'
        api: 'openai-completions'
        baseURL: '${channelA.baseURL}'
        models:
${models(channelA, channelA.models).map(m => `          - { id: '${m.id}', name: '${m.name}', contextWindow: ${m.contextWindow}, maxTokens: ${m.maxTokens} }`).join('\n')}
      real-b:
        apiKeyEnv: REAL_B_KEY
        displayName: 'Real B (newapi)'
        api: 'openai-completions'
        baseURL: '${channelB.baseURL}'
        models:
${models(channelB, channelB.models).map(m => `          - { id: '${m.id}', name: '${m.name}', contextWindow: ${m.contextWindow}, maxTokens: ${m.maxTokens} }`).join('\n')}
${scenario === 'transport' ? `      real-dead:
        apiKeyEnv: REAL_A_KEY
        displayName: 'Real Dead (connection refused)'
        api: 'openai-completions'
        baseURL: 'http://127.0.0.1:9/v1'
        models:
          - { id: 'kimi-k3', name: 'kimi-k3', contextWindow: 65536, maxTokens: 8192 }
` : ''}${scenario === 'server' && channelC !== undefined ? `      real-c:
        apiKeyEnv: REAL_C_KEY
        displayName: 'Real C (newapi)'
        api: 'openai-completions'
        baseURL: '${channelC.baseURL}'
        models:
${models(channelC, channelC.models).map(m => `          - { id: '${m.id}', name: '${m.name}', contextWindow: ${m.contextWindow}, maxTokens: ${m.maxTokens} }`).join('\n')}
` : ''}

- id: agent-default-model
  config:
    provider: ${BROKEN.provider}
    model: ${BROKEN.model}

- insert:
    - id: model-desk
      name: '${path.join(repo, 'packages', 'dsh-model-desk', 'lib', 'index.js').replace(/\\/g, '/')}'
      config:
        enabled: true
        policyVersion: 2
        defaultChainId: real-failover
        chains:
          - id: real-failover
            # The broken route is the implicit first hop: it is the model the
            # user selected (agent-default-model above), not a chain candidate.
            # Listing it here as well would be a second source of truth for the
            # same route. The old profiles shape this file used to write also
            # ignored maxRetries (it migrated maxAttempts), so the attempt count
            # came from the default budget.
            candidates:
              - { provider: '${BACKUP.provider}', model: '${BACKUP.model}', maxRetries: 0 }
            switchOn: { ${switchOnYaml} }
`

mkdirSync(here, { recursive: true })
const overlayPath = path.join(here, 'overlay-real.yml')
writeFileSync(overlayPath, overlay)

rmSync(path.join(here, '.sessions'), { recursive: true, force: true })
const started = Date.now()
const run = spawnSync(process.execPath, [
  path.join(repo, 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js'),
  '--profile', 'headless',
  '--patch', overlayPath.replace(/\\/g, '/'),
  'reply with the single word OK',
], {
  cwd: here,
  encoding: 'utf8',
  timeout: 240_000,
  env: {
    ...process.env,
    DSH_HOME,
    REAL_A_KEY: channelA.apiKey,
    REAL_B_KEY: channelB.apiKey,
    ...(channelC === undefined ? {} : { REAL_C_KEY: channelC.apiKey }),
  },
})
console.log(run.stdout ?? '')
if (run.stderr) console.error(run.stderr)
if (run.error !== undefined) {
  console.error(`spawn failed: ${String(run.error)}`)
  process.exit(1)
}

// ---- assertions on the durable session log ----
const { readdirSync, readFileSync: read } = await import('node:fs')
const sessionsRoot = path.join(here, '.sessions')
let logFile
try {
  const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap(entry =>
    entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)])
  logFile = walk(sessionsRoot).find(f => f.endsWith('.jsonl'))
} catch {
  console.error('no session log was written')
  process.exit(1)
}
if (logFile === undefined) {
  console.error(`no .jsonl under ${sessionsRoot} — the overlay pins the persistence root there`)
  process.exit(1)
}
const events = read(logFile, 'utf8').trim().split('\n').map(line => JSON.parse(line))
const headers = events.filter(e => e.type === 'request/header').map(e => `${e.data.header.config.provider}/${e.data.header.config.model}`)
const attempts = events.filter(e => e.type === 'assistant/attempt').map(e => {
  const finish = [...e.data.stream].reverse().find(r => r.chunk?.type === 'finish')
  return { turn: e.data.turn, step: e.data.step, kind: finish?.chunk?.reason?.kind, code: finish?.chunk?.reason?.failure?.code, message: finish?.chunk?.reason?.failure?.message }
})
const notices = events.filter(e => e.type === 'user/message' && e.data.source?.kind === 'model-desk').map(e => e.data.source.summary)
const hasAssistant = events.some(e => e.type === 'assistant/message')

let failures = 0
const check = (name, ok, detail) => {
  console.log(`  ${ok ? 'ok  ' : 'FAIL'} ${name}${ok || detail === undefined ? '' : `: ${detail}`}`)
  if (!ok) failures += 1
}

console.log(`\nreal-provider failover [${scenario}] (${((Date.now() - started) / 1000).toFixed(1)}s):`)
check('two routes: broken selection first, backup second', JSON.stringify(headers) === JSON.stringify([`${BROKEN.provider}/${BROKEN.model}`, `${BACKUP.provider}/${BACKUP.model}`]), JSON.stringify(headers))
check('the broken route really failed', attempts.length >= 2 && attempts[0].kind === 'error' && attempts[0].code !== undefined, JSON.stringify(attempts[0]))
// A code the named table does not know is not "ineligible": it is handled by the
// fallback key, which is exactly the path a gateway 5xx-without-status takes.
const brokenKey = attempts[0]?.code === undefined ? 'other' : switchOnKeyOf(attempts[0].code) ?? 'other'
check('the failure code is one this chain switches on', SWITCH_ON[brokenKey] === true,
  `${String(attempts[0]?.code)} -> ${brokenKey}`)
if (scenario === 'transport') {
  check('the transport failure is a real connection refusal', attempts[0]?.code === 'TRANSPORT', `${String(attempts[0]?.code)} — ${String(attempts[0]?.message ?? '')}`)
}
check('a Chinese failover notice names the backup', notices.some(n => n.includes(BACKUP.model)), JSON.stringify(notices))
check('the turn completed with an assistant message', hasAssistant)

console.log(`\n${failures === 0 ? 'PASS' : 'FAIL'}: ${failures} failure(s)`)
console.log(`failure code observed: ${attempts[0]?.code ?? 'none'} — ${attempts[0]?.message ?? ''}`)
process.exit(failures === 0 ? 0 : 1)

